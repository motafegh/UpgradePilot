"""Connect retained provider instances to the existing static command readers.

The base workflow remains the source of step membership and precedence. A derived
job view supplies specialized field values while script addresses identify the exact
generated bytes. Neither the view nor its address is a runtime association.
"""

from __future__ import annotations

from dataclasses import dataclass, replace

from .workflow_definition import (
    GitHubActionsStaticValue,
    RunDefaults,
    RunStepDefinition,
    StaticMappingValue,
    StaticScalarValue,
    StaticSequenceValue,
    StepsJobDefinition,
    UsesStepDefinition,
    WorkflowDefinition,
)
from .workflow_specialization import (
    FieldPath,
    SpecializedWorkflowField,
    WorkflowJobInstance,
    WorkflowJobInstanceIdentity,
)


@dataclass(frozen=True, slots=True)
class WorkflowRunScriptIdentity:
    """Address of one job instance's decoded run text, before shell analysis."""

    instance: WorkflowJobInstanceIdentity
    step_source_index: int
    script_digest: str


def run_script_identity(
    instance: WorkflowJobInstance, step_source_index: int,
) -> WorkflowRunScriptIdentity | None:
    path = ("steps", step_source_index, "run")
    for field in instance.fields:
        if field.path == path and field.generated_digest is not None:
            return WorkflowRunScriptIdentity(
                instance.identity, step_source_index, field.generated_digest,
            )
    return None


def materialize_workflow_job_instance(
    definition: WorkflowDefinition, instance: WorkflowJobInstance,
) -> StepsJobDefinition:
    """Overlay provider-resolved values without rewriting or reparsing YAML.

    Keep unresolved fields in place so dynamic higher-precedence declarations
    continue to block fallback. Conditions keep their original meaning.
    """
    identity = instance.identity
    if not 0 <= identity.job_source_index < len(definition.jobs):
        raise ValueError("Job instance has no retained source job.")
    job = definition.jobs[identity.job_source_index]
    if not isinstance(job, StepsJobDefinition) or job.key != identity.job_key:
        raise ValueError("Job instance differs from its retained source job.")
    fields = {field.path: field for field in instance.fields}
    if identity.kind == "ordinary":
        return job

    def specialize(
        value: GitHubActionsStaticValue | None, path: FieldPath,
    ) -> GitHubActionsStaticValue | None:
        if isinstance(value, StaticScalarValue):
            field = fields.get(path)
            if field is None or field.generated_text is None:
                return value
            if (field.original_text, field.original_span) != (value.text, value.span):
                raise ValueError("Specialized field differs from its original source field.")
            text = field.generated_text
            return replace(value, text=text, contains_expression="${{" in text)
        if isinstance(value, StaticSequenceValue):
            return replace(value, items=tuple(
                specialize(item, path + (index,))
                for index, item in enumerate(value.items)
            ))
        if isinstance(value, StaticMappingValue):
            return replace(value, entries=tuple(
                replace(entry, value=specialize(entry.value, path + (entry.key.text,)))
                for entry in value.entries
            ))
        return None

    def defaults(value: RunDefaults | None) -> RunDefaults | None:
        if value is None:
            return None
        return replace(
            value,
            shell=specialize(value.shell, ("defaults", "run", "shell")),
            working_directory=specialize(
                value.working_directory, ("defaults", "run", "working-directory"),
            ),
        )

    steps = []
    for step in job.steps:
        path = ("steps", step.source_index)
        if isinstance(step, (RunStepDefinition, UsesStepDefinition)):
            step = replace(
                step,
                name=specialize(step.name, path + ("name",)),
                environment=specialize(step.environment, path + ("env",)),
                continue_on_error=specialize(
                    step.continue_on_error, path + ("continue-on-error",),
                ),
            )
        if isinstance(step, RunStepDefinition):
            step = replace(
                step,
                command=specialize(step.command, path + ("run",)),
                shell=specialize(step.shell, path + ("shell",)),
                working_directory=specialize(
                    step.working_directory, path + ("working-directory",),
                ),
            )
        if isinstance(step, UsesStepDefinition):
            step = replace(step, with_inputs=specialize(step.with_inputs, path + ("with",)))
        steps.append(step)
    return replace(
        job,
        name=specialize(job.name, ("name",)),
        runs_on=specialize(job.runs_on, ("runs-on",)),
        container=specialize(job.container, ("container",)),
        environment=specialize(job.environment, ("env",)),
        continue_on_error=specialize(job.continue_on_error, ("continue-on-error",)),
        run_defaults=defaults(job.run_defaults),
        steps=tuple(steps),
    )
