"""Literal GitHub matrix expansion used by workflow_specialization.

This provider-local reader retains scalar kinds, spelling and source marks from the
same guarded YAML composition as the base definition. It interprets only ADR-0014's
qualified literal/comparison subset. No scheduler, expression engine or runtime
observation is involved. A rejected/over-limit expansion returns no partial positives.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import product
import math
import re
from typing import Literal

from yaml.nodes import MappingNode, Node, ScalarNode, SequenceNode

from .workflow_definition import SourceSpan, _span

MATRIX_SPECIALIZATION_METHOD = "github_literal_matrix/1"
# GitHub's documented maximum jobs generated by a matrix in one workflow run.
MAX_MATRIX_JOBS = 256
# Whole-token numeric shapes only. A plain version such as 13.0.0 or a label
# such as 123abc is an unambiguous string, even though it begins with a digit.
_UNQUALIFIED_NUMBER = re.compile(
    r"[+-]?(?:(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?"
    r"|0[xX][0-9a-fA-F]+|0[oO][0-7]+|0[bB][01]+)"
)


@dataclass(frozen=True, slots=True)
class MatrixLiteral:
    kind: Literal["string", "integer", "boolean", "null"]
    value: str | int | bool | None
    spelling: str
    span: SourceSpan


@dataclass(frozen=True, slots=True)
class MatrixCoordinate:
    name: str
    literal: MatrixLiteral
    name_span: SourceSpan


@dataclass(frozen=True, slots=True)
class MatrixExpansionRow:
    coordinates: tuple[MatrixCoordinate, ...]
    # Axis indices distinguish repeated equal values; None means include-created.
    original_axis_indices: tuple[int, ...] | None
    include_indices: tuple[int, ...] = ()


@dataclass(frozen=True, slots=True)
class MatrixExpansionProblem:
    reason: str
    detail: str
    span: SourceSpan


@dataclass(frozen=True, slots=True)
class MatrixExpansion:
    state: Literal["complete", "unresolved", "incomplete"]
    rows: tuple[MatrixExpansionRow, ...]
    problem: MatrixExpansionProblem | None = None


class _MatrixRefusal(ValueError):
    def __init__(self, reason: str, detail: str, node: Node) -> None:
        self.problem = MatrixExpansionProblem(reason, detail, _span(node))


def _refuse(reason: str, detail: str, node: Node) -> None:
    raise _MatrixRefusal(reason, detail, node)


def read_matrix_literal(node: Node, source_text: str) -> MatrixLiteral:
    """Read a typed scalar without PyYAML's YAML-1.1 implicit conversions."""
    if not isinstance(node, ScalarNode):
        _refuse("matrix_non_scalar_value", "Matrix values must be admitted scalars.", node)
    assert isinstance(node, ScalarNode)
    spelling = source_text[node.start_mark.index:node.end_mark.index]
    text = node.value
    if node.tag != "tag:yaml.org,2002:str" or re.match(r"(?:&\S+\s+)?!", spelling):
        _refuse("matrix_explicit_tag_unsupported", "Explicit scalar tags are unqualified.", node)
    if "${{" in text:
        _refuse("matrix_dynamic_value", "Matrix values containing expressions remain unresolved.", node)
    if node.style is not None:
        kind, value = "string", text
    elif text in {"true", "True", "TRUE", "false", "False", "FALSE"}:
        kind, value = "boolean", text.lower() == "true"
    elif text in {"", "~", "null", "Null", "NULL"}:
        kind, value = "null", None
    elif re.fullmatch(r"[+-]?(?:0|[1-9][0-9]*)", text):
        if len(text) > 310:
            _refuse("matrix_integer_precision_unsupported", "Integer exceeds the qualified numeric model.", node)
        value = int(text)
        try:
            numeric = float(value)
        except OverflowError:
            _refuse("matrix_integer_precision_unsupported", "Integer exceeds the provider numeric range.", node)
        if not math.isfinite(numeric) or int(numeric) != value:
            _refuse("matrix_integer_precision_unsupported", "Integer is not exactly representable as a provider number.", node)
        kind = "integer"
    elif "_" not in text and (
        _UNQUALIFIED_NUMBER.fullmatch(text)
        or text.lower() in {".nan", ".inf", "+.inf", "-.inf"}
    ):
        _refuse("matrix_numeric_spelling_unsupported", "Numeric conversion needs further characterization.", node)
    else:
        kind, value = "string", text
    return MatrixLiteral(kind, value, spelling, _span(node))


def _mapping(node: Node) -> tuple[tuple[ScalarNode, Node], ...]:
    if not isinstance(node, MappingNode):
        _refuse("matrix_mapping_required", "Expected a literal mapping.", node)
    pairs = []
    seen = set()
    for key, value in node.value:
        if not isinstance(key, ScalarNode) or not key.value or "${{" in key.value:
            _refuse("matrix_key_unsupported", "Matrix keys must be nonempty literal strings.", key)
        folded = key.value.casefold()
        if folded in seen:
            _refuse("matrix_key_collision", "Duplicate or case-colliding matrix keys are ambiguous.", key)
        seen.add(folded)
        pairs.append((key, value))
    return tuple(pairs)


def _rows(node: Node, source_text: str) -> tuple[tuple[MatrixCoordinate, ...], ...]:
    if not isinstance(node, SequenceNode):
        _refuse("matrix_rows_not_sequence", "Matrix include/exclude must be a literal sequence.", node)
    return tuple(
        tuple(MatrixCoordinate(key.value, read_matrix_literal(value, source_text), _span(key))
              for key, value in _mapping(row))
        for row in node.value
    )


def _typed_equal(left: MatrixLiteral, right: MatrixLiteral) -> bool:
    return left.kind == right.kind and left.value == right.value


def _coordinate_map(row: tuple[MatrixCoordinate, ...]) -> dict[str, MatrixCoordinate]:
    return {item.name.casefold(): item for item in row}


def _qualify_comparisons(rows: tuple[tuple[MatrixCoordinate, ...], ...], node: Node) -> None:
    values: dict[str, list[MatrixLiteral]] = {}
    for row in rows:
        for coordinate in row:
            values.setdefault(coordinate.name.casefold(), []).append(coordinate.literal)
    for literals in values.values():
        if len({literal.kind for literal in literals}) > 1:
            _refuse("matrix_mixed_comparison_kinds", "Compared values must have one qualified scalar kind per property.", node)
        strings: dict[str, str] = {}
        for literal in literals:
            if literal.kind == "string":
                text = str(literal.value)
                previous = strings.setdefault(text.casefold(), text)
                if previous != text:
                    _refuse("matrix_case_only_value_collision", "Case-only string comparisons remain unqualified.", node)


def expand_literal_matrix(strategy: Node, source_text: str) -> MatrixExpansion:
    """Expand axes, exclude partial matches, then apply includes to original rows.

    A limit failure is atomic, including a Cartesian set that exclusions might later
    shrink. This bounds work before product allocation and never labels truncation as
    complete. Include-created rows never become eligible originals for later includes.
    """
    try:
        return _expand_literal_matrix(strategy, source_text)
    except _MatrixRefusal as exc:
        state = "incomplete" if exc.problem.reason == "matrix_expansion_limit" else "unresolved"
        return MatrixExpansion(state, (), exc.problem)


def _expand_literal_matrix(strategy: Node, source_text: str) -> MatrixExpansion:
    strategy_fields = {key.value: value for key, value in _mapping(strategy)}
    if set(strategy_fields) - {"matrix", "fail-fast", "max-parallel"}:
        _refuse("matrix_strategy_field_unsupported", "Unrecognized strategy fields remain unresolved.", strategy)
    matrix = strategy_fields.get("matrix")
    if matrix is None:
        _refuse("matrix_declaration_missing", "Strategy does not contain a literal matrix.", strategy)
    axes = []
    includes = ()
    excludes = ()
    count = 1
    for key, value in _mapping(matrix):
        if key.value in {"include", "exclude"}:
            if key.value == "include":
                includes = _rows(value, source_text)
            else:
                excludes = _rows(value, source_text)
            continue
        if not isinstance(value, SequenceNode) or not value.value:
            _refuse("matrix_axis_not_nonempty_sequence", "Each axis needs a nonempty literal sequence.", value)
        literals = tuple(MatrixCoordinate(key.value, read_matrix_literal(item, source_text), _span(key))
                         for item in value.value)
        axes.append(literals)
        count *= len(literals)
        if count > MAX_MATRIX_JOBS:
            _refuse("matrix_expansion_limit", "Cartesian expansion exceeds the provider matrix bound.", matrix)
    if not axes and not includes:
        _refuse("matrix_empty_declaration", "No axis combinations or include rows are declared.", matrix)
    # Bound include work as well as generated output; input traversal is also guarded.
    if len(includes) > MAX_MATRIX_JOBS:
        _refuse("matrix_expansion_limit", "Include rows exceed the bounded matrix work budget.", matrix)
    _qualify_comparisons(tuple(axes) + includes + excludes, matrix)
    original = []
    if axes:
        for indices in product(*(range(len(axis)) for axis in axes)):
            coordinates = tuple(axes[i][index] for i, index in enumerate(indices))
            values = _coordinate_map(coordinates)
            if any(all(item.name.casefold() in values and _typed_equal(
                values[item.name.casefold()].literal, item.literal) for item in row) for row in excludes):
                continue
            original.append(MatrixExpansionRow(coordinates, indices))
    rows = list(original)
    for include_index, include in enumerate(includes):
        included = _coordinate_map(include)
        applied = False
        for index, base in enumerate(original):
            base_values = _coordinate_map(base.coordinates)
            if any(name in base_values and not _typed_equal(base_values[name].literal, item.literal)
                   for name, item in included.items()):
                continue
            merged = _coordinate_map(rows[index].coordinates)
            merged.update(included)
            rows[index] = MatrixExpansionRow(tuple(merged.values()), base.original_axis_indices,
                                              rows[index].include_indices + (include_index,))
            applied = True
        if not applied:
            rows.append(MatrixExpansionRow(include, None, (include_index,)))
        if len(rows) > MAX_MATRIX_JOBS:
            _refuse("matrix_expansion_limit", "Expanded matrix exceeds the provider job bound.", matrix)
    return MatrixExpansion("complete", tuple(rows))
